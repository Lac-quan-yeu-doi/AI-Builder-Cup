import { createHash } from 'node:crypto';

import { DATAFRAME_EMITTERS } from '@application/pipeline-compilation/emitters/dataframe.emitters';
import { SOURCE_TARGET_EMITTERS } from '@application/pipeline-compilation/emitters/source-target.emitters';
import { PipelineEmitterRegistry } from '@application/pipeline-compilation/emitter-registry';
import {
  normalizeGraph,
  semanticGraphHash,
} from '@application/pipeline-compilation/graph-normalizer';
import type { NodeCompileContext } from '@application/pipeline-compilation/pipeline-ir';
import { PythonCodeWriter } from '@application/pipeline-compilation/python-code-writer';
import { pythonLiteral } from '@application/pipeline-compilation/python-literal';
import { RUNTIME_PREAMBLE } from '@application/pipeline-compilation/runtime-preamble';
import { topologicalSort } from '@application/pipeline-compilation/topological-sort';
import type { NodeDefinition } from '@domain/node-catalog/models/node-definition';
import type { PipelineGraph, PipelineNode } from '@domain/pipeline-authoring/models/pipeline';
import { PipelineCompilationError } from '@domain/pipeline-compilation/errors/pipeline-compilation.error';
import type { CompiledPipeline } from '@domain/pipeline-compilation/models/compiled-pipeline';

export const PIPELINE_COMPILER_VERSION = '1.2.3';
export const OUTPUT_FACTS_CAPABILITY_MARKER = 'CELESNITY_OUTPUT_FACTS_V1';

export interface CompilePipelineInput {
  readonly pipelineId: string;
  readonly pipelineVersion: number;
  readonly pipelineName: string;
  readonly graph: PipelineGraph;
  readonly definitionsByNodeId: ReadonlyMap<string, NodeDefinition>;
}

export class PipelineCompiler {
  public constructor(
    private readonly registry = new PipelineEmitterRegistry([
      ...SOURCE_TARGET_EMITTERS,
      ...DATAFRAME_EMITTERS,
    ]),
  ) {}

  public compile(input: CompilePipelineInput): CompiledPipeline {
    const graph = normalizeGraph(input.graph);
    this.validateCompilationShape(graph, input.definitionsByNodeId);
    const graphHash = semanticGraphHash(graph);
    const order = topologicalSort(graph);
    const outputVariables = new Map<string, string>();
    const writer = new PythonCodeWriter();

    writer.block([
      '# ----------------------------------------------------------------------',
      '# GENERATED BY CELESNITY - DO NOT EDIT',
      `# Pipeline: ${safeComment(input.pipelineName)}`,
      `# Pipeline ID: ${safeComment(input.pipelineId)}`,
      `# Pipeline version: ${String(input.pipelineVersion)}`,
      `# Compiler version: ${PIPELINE_COMPILER_VERSION}`,
      `# ${OUTPUT_FACTS_CAPABILITY_MARKER}`,
      `# Semantic graph SHA-256: ${graphHash}`,
      '# ----------------------------------------------------------------------',
      '',
      ...RUNTIME_PREAMBLE,
      '',
      `PIPELINE_ID = ${pythonLiteral(input.pipelineId)}`,
      `PIPELINE_VERSION = ${String(input.pipelineVersion)}`,
      `COMPILER_VERSION = ${pythonLiteral(PIPELINE_COMPILER_VERSION)}`,
      `SEMANTIC_GRAPH_SHA256 = ${pythonLiteral(graphHash)}`,
      '',
      '',
      'def main() -> None:',
      '    parser = argparse.ArgumentParser()',
      '    parser.add_argument("--execution-id", required=True)',
      '    parser.add_argument("--workflow-facts-plan-ref", required=False)',
      '    parser.add_argument("--job-name", required=False)',
      '    args = parser.parse_args()',
      '    workflow_output_plan = load_workflow_output_plan(args.workflow_facts_plan_ref)',
      '    job_name = args.job_name or f"pipeline-{PIPELINE_ID}-v{PIPELINE_VERSION}"',
      '    spark = build_spark(job_name)',
      '    try:',
      '        emit_event("PIPELINE_STARTED", executionId=args.execution_id)',
    ]);

    for (const node of order) {
      const definition = this.requireDefinition(input.definitionsByNodeId, node);
      const emitter = this.registry.require(node.definitionType, node.id);
      const inputs = this.resolveInputs(graph, node, outputVariables, input.definitionsByNodeId);
      const context = this.context(node, definition, inputs);
      const config = emitter.parseConfig(node.config, node.id);
      const fragment = emitter.emit(context, config);
      const displayName = nodeName(node, definition);
      const lines = [
        '',
        `        # Script generated for node ${safeComment(displayName)}`,
        `        emit_event("NODE_STARTED", nodeId=${pythonLiteral(node.id)}, nodeName=${pythonLiteral(displayName)}, nodeType=${pythonLiteral(node.definitionType)})`,
        ...fragment.lines.map((line) => `        ${line}`),
        definition.category === 'TARGET'
          ? `        emit_event("NODE_SUCCEEDED", nodeId=${pythonLiteral(node.id)})`
          : `        emit_event("NODE_PLANNED", nodeId=${pythonLiteral(node.id)})`,
      ];
      writer.nodeBlock(node.id, lines);
      for (const [portId, variable] of fragment.outputs) {
        outputVariables.set(outputKey(node.id, portId), variable);
      }
    }

    writer.block([
      '',
      '        emit_event("PIPELINE_SUCCEEDED")',
      '    except Exception as error:',
      '        emit_event("PIPELINE_FAILED", errorType=type(error).__name__, message=str(error))',
      '        traceback.print_exc()',
      '        raise',
      '    finally:',
      '        spark.stop()',
      '',
      '',
      'if __name__ == "__main__":',
      '    main()',
    ]);

    const rendered = writer.render();
    return {
      source: rendered.source,
      sourceSha256: createHash('sha256').update(rendered.source).digest('hex'),
      semanticGraphSha256: graphHash,
      compilerVersion: PIPELINE_COMPILER_VERSION,
      sourceMap: rendered.sourceMap,
    };
  }

  private validateCompilationShape(
    graph: PipelineGraph,
    definitions: ReadonlyMap<string, NodeDefinition>,
  ): void {
    const categories = graph.nodes.map(
      (node) => this.requireDefinition(definitions, node).category,
    );
    const sourceCount = categories.filter((category) => category === 'SOURCE').length;
    if (sourceCount !== 1) {
      throw PipelineCompilationError.issue(
        'SOURCE_COUNT_UNSUPPORTED',
        'The first pipeline compiler release requires exactly one source.',
      );
    }
    if (!categories.includes('TARGET')) {
      throw PipelineCompilationError.issue(
        'PIPELINE_NOT_COMPILABLE',
        'The pipeline requires at least one target.',
      );
    }
    for (const edge of graph.edges) {
      const source = graph.nodes.find((node) => node.id === edge.sourceNodeId);
      if (source?.definitionType === 'FILTER' && edge.sourcePortId === 'rejected') {
        throw PipelineCompilationError.issue(
          'LEGACY_FILTER_REJECTED_UNSUPPORTED',
          'FILTER now keeps matched rows only; the rejected branch must be removed or redesigned.',
          { nodeId: source.id },
        );
      }
    }
  }

  private resolveInputs(
    graph: PipelineGraph,
    node: PipelineNode,
    outputs: ReadonlyMap<string, string>,
    definitions: ReadonlyMap<string, NodeDefinition>,
  ): ReadonlyMap<string, string> {
    const inputs = new Map<string, string>();
    for (const edge of graph.edges.filter((candidate) => candidate.targetNodeId === node.id)) {
      const source = graph.nodes.find((candidate) => candidate.id === edge.sourceNodeId);
      if (source === undefined) {
        throw PipelineCompilationError.issue(
          'NODE_INPUT_MISSING',
          'An input edge references a missing source node.',
          { nodeId: node.id },
        );
      }
      const sourceDefinition = this.requireDefinition(definitions, source);
      const sourcePort =
        sourceDefinition.type === 'FILTER' && edge.sourcePortId === 'matched'
          ? 'output'
          : edge.sourcePortId;
      const variable = outputs.get(outputKey(source.id, sourcePort));
      if (variable === undefined) {
        throw PipelineCompilationError.issue(
          'NODE_OUTPUT_MISSING',
          `The upstream output ${source.id}:${sourcePort} is unavailable.`,
          { nodeId: node.id },
        );
      }
      inputs.set(edge.targetPortId, variable);
    }
    return inputs;
  }

  private context(
    node: PipelineNode,
    definition: NodeDefinition,
    inputs: ReadonlyMap<string, string>,
  ): NodeCompileContext {
    return {
      node,
      definition,
      inputs,
      variableForOutput: (portId) => variableName(node, definition, portId),
      requireInput: (portId: string): string => {
        const value = inputs.get(portId);
        if (value === undefined) {
          throw PipelineCompilationError.issue(
            'NODE_INPUT_MISSING',
            `Node input port ${portId} is not connected.`,
            { nodeId: node.id },
          );
        }
        return value;
      },
    };
  }

  private requireDefinition(
    definitions: ReadonlyMap<string, NodeDefinition>,
    node: PipelineNode,
  ): NodeDefinition {
    const definition = definitions.get(node.id);
    if (definition === undefined) {
      throw PipelineCompilationError.issue(
        'PIPELINE_NOT_COMPILABLE',
        'A node definition could not be resolved.',
        { nodeId: node.id },
      );
    }
    return definition;
  }
}

function variableName(node: PipelineNode, definition: NodeDefinition, portId: string): string {
  const label = nodeName(node, definition)
    .normalize('NFKD')
    .replace(/[^A-Za-z0-9_]/gu, '_')
    .replace(/_+/gu, '_')
    .replace(/^_+|_+$/gu, '');
  const prefix = label === '' || /^\d/u.test(label) ? `Node_${label}` : label;
  const suffix = createHash('sha256').update(`${node.id}:${portId}`).digest('hex').slice(0, 12);
  return `${prefix}_node${suffix}`;
}

function nodeName(node: PipelineNode, definition: NodeDefinition): string {
  const configured = node.config.name;
  return typeof configured === 'string' && configured.trim() !== ''
    ? configured.trim()
    : definition.label;
}

function outputKey(nodeId: string, portId: string): string {
  return `${nodeId}\u0000${portId}`;
}

function safeComment(value: string): string {
  return value.replace(/[\r\n\u2028\u2029]+/gu, ' ').trim();
}
