  'def write_iceberg_target_with_output_facts(frame: DataFrame, namespace: str, table: str, mode: str, target_node_id: str, execution_id: str, output_plan: dict[str, list[dict[str, object]]]) -> None:',
  '    predicates = output_plan.get(target_node_id)',
  '    final_target = qualified_iceberg_table(namespace, table)',
  '    if predicates is None:',
  '        _write_final_target(frame, final_target, mode)',
  '        return',
  '    if re.fullmatch(r"[0-9a-fA-F-]{36}", execution_id) is None:',
