  'def drop_all_null_columns(frame: DataFrame) -> DataFrame:',
  '    if not frame.columns:',
  '        return frame',
  '    present = frame.agg(*[',
  '        F.max(F.when(F.col(name).isNotNull(), F.lit(1)).otherwise(F.lit(0))).alias(name)',
  '        for name in frame.columns',
  '    ]).first().asDict()',
  '    return frame.select(*[F.col(name) for name in frame.columns if present.get(name) == 1])',
