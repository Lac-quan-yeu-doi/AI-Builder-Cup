  'def load_workflow_output_plan(path: str | None) -> dict[str, list[dict[str, object]]]:',
  '    if path is None:',
  '        return {}',
  '    if os.path.getsize(path) > 524288:',
  '        raise RuntimeError("Workflow output condition plan exceeds its size bound")',
  '    with open(path, "r", encoding="utf-8") as handle:',
  '        payload = json.load(handle)',
  '    if not isinstance(payload, dict) or set(payload) != {"targets"} or not isinstance(payload["targets"], list):',
  '        raise RuntimeError("Workflow output condition plan is invalid")',
  '    targets: dict[str, list[dict[str, object]]] = {}',
  '    branches: set[str] = set()',
  '    predicate_count = 0',
  '    if not 1 <= len(payload["targets"]) <= 32:',
  '        raise RuntimeError("Workflow output condition target count is invalid")',
  '    for target in payload["targets"]:',
  '        if not isinstance(target, dict) or set(target) != {"targetNodeId", "predicates"}:',
  '            raise RuntimeError("Workflow output condition target is invalid")',
  '        target_id = target["targetNodeId"]',
  '        predicates = target["predicates"]',
  '        if not _valid_workflow_identifier(target_id) or target_id in targets or not isinstance(predicates, list) or not predicates:',
  '            raise RuntimeError("Workflow output condition target is invalid")',
  '        targets[target_id] = []',
  '        for predicate in predicates:',
  '            if not isinstance(predicate, dict):',
  '                raise RuntimeError("Workflow output predicate is invalid")',
  '            allowed = {"branchId", "column", "operator", "value"}',
  '            if set(predicate) - allowed or not {"branchId", "column", "operator"}.issubset(predicate):',
  '                raise RuntimeError("Workflow output predicate is invalid")',
  '            branch_id = predicate["branchId"]',
  '            column = predicate["column"]',
  '            operator = predicate["operator"]',
  '            if not _valid_workflow_identifier(branch_id) or branch_id in branches or not _valid_workflow_identifier(column):',
  '                raise RuntimeError("Workflow output predicate is invalid")',
  '            if operator not in {"EQ", "NE", "GT", "GTE", "LT", "LTE", "IS_EMPTY", "IS_NOT_EMPTY"}:',
  '                raise RuntimeError("Workflow output predicate operator is invalid")',
  '            if operator in {"IS_EMPTY", "IS_NOT_EMPTY"}:',
  '                if "value" in predicate:',
  '                    raise RuntimeError("Empty-value predicate must not include a value")',
  '            elif "value" not in predicate or not _valid_workflow_scalar(predicate["value"]):',
  '                raise RuntimeError("Workflow output predicate value is invalid")',
  '            elif operator in {"GT", "GTE", "LT", "LTE"} and (isinstance(predicate["value"], bool) or not isinstance(predicate["value"], (int, float, str))):',
  '                raise RuntimeError("Ordered workflow output predicate value is invalid")',
  '            if isinstance(predicate.get("value"), str) and len(predicate["value"]) > 4096:',
  '                raise RuntimeError("Workflow output predicate string exceeds its size bound")',
  '            if isinstance(predicate.get("value"), float) and not math.isfinite(predicate["value"]):',
  '                raise RuntimeError("Workflow output predicate number is invalid")',
  '            branches.add(branch_id)',
  '            targets[target_id].append(predicate)',
  '            predicate_count += 1',
  '            if predicate_count > 128:',
  '                raise RuntimeError("Workflow output predicate count is invalid")',
  '    return targets',
  '',
