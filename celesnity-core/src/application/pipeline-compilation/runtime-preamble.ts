  '    catalog = os.environ.get("ICEBERG_CATALOG", "celesnity") + "_workflow_staging"',
  '    stage_id = "_execution_" + str(int(time.time())).zfill(10) + "_" + execution_id.replace("-", "").lower() + "_" + uuid.uuid4().hex + "_" + hashlib.sha256(target_node_id.encode("utf-8")).hexdigest()[:12]',
  '    stage_table = qualified_staging_iceberg_table(stage_namespace, stage_id)',
  '    try:',
  '        spark.sql("CREATE NAMESPACE IF NOT EXISTS " + quote_iceberg_identifier(catalog) + "." + quote_iceberg_identifier(stage_namespace))',
