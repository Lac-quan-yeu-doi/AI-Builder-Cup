  'def fill_missing_value(frame: DataFrame, field: str, strategy: str, literal: object) -> DataFrame:',
  '    if strategy == "LITERAL":',
  '        replacement = literal',
  '    elif strategy == "MEAN":',
  '        replacement = frame.select(F.avg(F.col(field))).first()[0]',
  '    elif strategy == "MEDIAN":',
  '        values = frame.approxQuantile(field, [0.5], 0.001)',
  '        replacement = values[0] if values else None',
  '    elif strategy == "MODE":',
  '        row = (frame.where(F.col(field).isNotNull()).groupBy(field).count()',
  '               .orderBy(F.col("count").desc(), F.col(field).asc()).first())',
  '        replacement = None if row is None else row[field]',
  '    else:',
  '        raise ValueError(f"Unsupported fill strategy: {strategy}")',
  '    return frame if replacement is None else frame.fillna({field: replacement})',
