  'def _workflow_predicate_expression(predicate: dict[str, object]):',
  '    column = _workflow_predicate_column(str(predicate["column"]))',
  '    operator = predicate["operator"]',
  '    if operator == "IS_EMPTY":',
  '        return column.isNull() | (F.trim(column.cast("string")) == F.lit(""))',
  '    if operator == "IS_NOT_EMPTY":',
  '        return column.isNotNull() & (F.trim(column.cast("string")) != F.lit(""))',
  '    if predicate["value"] is None:',
  '        if operator == "EQ":',
  '            return column.isNull()',
  '        if operator == "NE":',
  '            return column.isNotNull()',
  '        raise RuntimeError("Ordered workflow output predicate cannot compare null")',
  '    value = F.lit(predicate["value"])',
  '    return {',
  '        "EQ": lambda: column == value,',
  '        "NE": lambda: column != value,',
  '        "GT": lambda: column > value,',
  '        "GTE": lambda: column >= value,',
  '        "LT": lambda: column < value,',
  '        "LTE": lambda: column <= value,',
  '    }[str(operator)]()',
