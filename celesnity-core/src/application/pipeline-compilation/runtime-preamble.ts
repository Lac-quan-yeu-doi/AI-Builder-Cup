  '        aliases: dict[str, str] = {}',
  '        for predicate in predicates:',
  '            branch_id = str(predicate["branchId"])',
  '            alias = "_match_" + hashlib.sha256(branch_id.encode("utf-8")).hexdigest()[:16]',
  '            aliases[branch_id] = alias',
  '            expressions.append(F.coalesce(F.sum(F.when(_workflow_predicate_expression(predicate), F.lit(1)).otherwise(F.lit(0))), F.lit(0)).alias(alias))',
  '        counts = materialized.agg(*expressions).first().asDict()',
  '        total_rows = int(counts["_total_rows"] or 0)',
  '        matches_by_branch_id = {branch_id: int(counts[alias] or 0) for branch_id, alias in aliases.items()}',
  '        _write_final_target(materialized, final_target, mode)',
  '        emit_event("PIPELINE_OUTPUT_FACTS", executionId=execution_id, targetNodeId=target_node_id, totalRows=total_rows, matchesByBranchId=matches_by_branch_id)',
  '    finally:',
  '        try:',
  '            spark.sql("DROP TABLE IF EXISTS " + stage_table + " PURGE").collect()',
  '        except Exception:',
  '            emit_event("PIPELINE_WARNING", code="OUTPUT_FACT_STAGING_CLEANUP_FAILED", targetNodeId=target_node_id)',
  '',
